import io, re
P = "報告/進度報告_1005_V2.tex"
s = io.open(P, encoding="utf-8").read()
N0 = {w: s.count(w) for w in [u"落差", u"脈絡", u"本文", u"換言之"]}
def sub(a, b, lab="", n=1):
    global s
    c = s.count(a); assert c == n, u"替換失敗（%d 次）：%s" % (c, (lab or a)[:40])
    s = s.replace(a, b)

