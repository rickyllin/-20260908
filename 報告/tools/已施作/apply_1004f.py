sub(u"見下文。另有一項結構上的落差。", u"見下文。另有一項結構上的差異。", u"落差4")
sub(u"""這條脈絡與小人口 Lee-Carter 之間的落差正在此處，而該落差有一半是有利的。""",
    u"""這一支與小人口 Lee-Carter 之間的差異正在此處，而該差異有一半是有利的。""",
    u"落差5")
sub(u"這條脈絡的標準設定與小人口 Lee-Carter 之間的落差亦有數處。",
    u"這一支的標準設定與小人口 Lee-Carter 之間的差異亦有數處。", u"落差6")
